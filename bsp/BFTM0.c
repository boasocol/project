  /* 使能BFTM0外设时钟 */
  /* CKCU（Clock Control Unit）负责管理所有外设的时钟开关 */
  CKCU_PeripClockConfig(CKCUClock, ENABLE);
  
  /* 使能BFTM0中断在NVIC中的通道 */
  /* NVIC（Nested Vectored Interrupt Controller）是ARM Cortex-M系列的中断控制器 */
  /* BFTM0_IRQn是BFTM0中断的中断号 */
