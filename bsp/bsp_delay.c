/************************************************************************************************************
 * @file    bsp_delay.c
 * @brief   BSP 通用毫秒延时（基于 BFTM0 的 1ms 节拍计数器 bftm0_ct）
 * @note    P1（2026-09-03）从 spi_lcd.c 迁出：延时是板级服务，不属于 LCD 驱动。
 *          休眠唤醒后 BFTM0 尚未恢复时调用会卡死（见 key.c 注释），调用方需保证时序。
 ************************************************************************************************************/
#include "bsp_delay.h"
#include "BFTM0.h"   /* bftm0_ct（1ms 节拍计数器） */

//-----------------------------------------------------------------------------
/**
 * @brief  毫秒级阻塞延时（基于 BFTM0 的 1ms 节拍计数器 bftm0_ct）
 * @param  ms : 延时毫秒数
 * @retval 无
 */
void Delay(u32 ms)
{
  vu32 target = bftm0_ct + ms;
  while (bftm0_ct < target);
}
