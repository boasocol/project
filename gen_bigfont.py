# -*- coding: utf-8 -*-
# gen_bigfont.py - generate a dedicated big 1bpp font (digits 0-9 + ':') for the clock.
# Rendered at native pixel size (no scaling on MCU), so edges are smooth.
# usage: python gen_bigfont.py
from PIL import Image, ImageDraw, ImageFont

TTF_PATH = r"C:\Windows\Fonts\consola.ttf"
SIZE     = 96                                # native pixel size (digit ink ~60px tall)
OUT_H    = r"c:\Users\q3112\Desktop\HT\4\HT32L52231_QFN32\project\bigfont.h"
OUT_C    = r"c:\Users\q3112\Desktop\HT\4\HT32L52231_QFN32\project\bigfont.c"
CHARS    = "0123456789:"                     # index 0..9 = digits, 10 = colon

def main():
    font = ImageFont.truetype(TTF_PATH, SIZE)

    raw = []
    for ch in CHARS:
        img = Image.new('1', (400, 400), 0)
        d = ImageDraw.Draw(img)
        d.text((40, 40), ch, font=font, fill=1)
        bb = img.getbbox()
        x0, y0, x1, y1 = bb
        w, h, top = x1 - x0, y1 - y0, y0 - 40
        raw.append((ch, w, h, top, img.crop((x0, y0, x1, y1))))

    # normalize: subtract common min top so yoff stays small (digits start at 0)
    min_top = min(t for (_, _, _, t, _) in raw)
    glyphs = []
    bits = bytearray()
    big_h = 0
    for (ch, w, h, top, crop) in raw:
        yoff = top - min_top
        big_h = max(big_h, yoff + h)
        pitch = (w + 7) // 8
        off = len(bits)
        for yy in range(h):
            byte, cnt = 0, 0
            for xx in range(w):
                bit = 1 if crop.getpixel((xx, yy)) else 0
                byte = (byte << 1) | bit
                cnt += 1
                if cnt == 8:
                    bits.append(byte); byte, cnt = 0, 0
            if cnt > 0:
                bits.append(byte << (8 - cnt))
        glyphs.append((ch, w, h, yoff, off, pitch))

    max_w = max(g[1] for g in glyphs)

    with open(OUT_H, 'w', encoding='utf-8') as f:
        f.write("/* Auto-generated by gen_bigfont.py: big clock font, src %s, size=%d */\n"
                % (TTF_PATH, SIZE))
        f.write("#ifndef __BIGFONT_H\n#define __BIGFONT_H\n#include \"ht32.h\"\n")
        f.write("#define BIGFONT_H     %d  /* total ink height (max yoff+h) */\n" % big_h)
        f.write("#define BIGFONT_MAX_W %d  /* widest glyph */\n" % max_w)
        f.write("#define BIGFONT_COLON 10  /* index of ':' */\n")
        f.write("typedef struct { u16 w; u16 h; u16 yoff; u16 off; u16 pitch; } BIG_GLYPH;\n")
        f.write("extern const BIG_GLYPH g_big_glyphs[%d];\n" % len(glyphs))
        f.write("extern const u8 g_big_bits[];\n#endif\n")

    with open(OUT_C, 'w', encoding='utf-8') as f:
        f.write("/* Auto-generated by gen_bigfont.py (1bpp, MSB first, row-major) */\n")
        f.write("#include \"bigfont.h\"\n")
        f.write("const BIG_GLYPH g_big_glyphs[%d] = {\n" % len(glyphs))
        for (ch, w, h, yoff, off, pitch) in glyphs:
            f.write("  {%d,%d,%d,%d,%d}, /* '%s' */\n" % (w, h, yoff, off, pitch, ch))
        f.write("};\n")
        f.write("const u8 g_big_bits[] = {\n")
        for i in range(0, len(bits), 16):
            f.write("  " + ",".join("0x%02X" % b for b in bits[i:i + 16]) + ",\n")
        f.write("};\n")
    print("OK glyphs=%d bits=%d bytes big_h=%d max_w=%d" % (len(glyphs), len(bits), big_h, max_w))
    for (ch, w, h, yoff, off, pitch) in glyphs:
        print("  '%s' w=%d h=%d yoff=%d" % (ch, w, h, yoff))

if __name__ == "__main__":
    main()
