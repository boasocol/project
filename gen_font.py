# -*- coding: utf-8 -*-
# gen_font.py - generate 1bpp bitmap font (font.c / font.h) from a system TTF.
# usage: python gen_font.py   (edit SIZE / TTF_PATH / FIRST..LAST as needed)
from PIL import Image, ImageDraw, ImageFont

TTF_PATH = r"C:\Windows\Fonts\consola.ttf"   # monospace, clean digits
SIZE     = 24                                # font size in px
OUT_H    = r"c:\Users\q3112\Desktop\HT\4\HT32L52231_QFN32\project\font.h"
OUT_C    = r"c:\Users\q3112\Desktop\HT\4\HT32L52231_QFN32\project\font.c"
FIRST, LAST = 32, 126                        # printable ASCII

def main():
    font = ImageFont.truetype(TTF_PATH, SIZE)
    asc, desc = font.getmetrics()
    em_h = asc + desc

    glyphs = []
    bits = bytearray()
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        img = Image.new('1', (400, 400), 0)
        d = ImageDraw.Draw(img)
        d.text((20, 20), ch, font=font, fill=1)
        bb = img.getbbox()
        if bb is None:                      # blank (space)
            glyphs.append((0, 0, 0, len(bits), 0))
            continue
        x0, y0, x1, y1 = bb
        w, h, yoff = x1 - x0, y1 - y0, y0 - 20
        crop = img.crop((x0, y0, x1, y1))
        pitch = (w + 7) // 8
        off = len(bits)
        for yy in range(h):
            byte, cnt = 0, 0
            for xx in range(w):
                bit = 1 if crop.getpixel((xx, yy)) else 0
                byte = (byte << 1) | bit
                cnt += 1
                if cnt == 8:
                    bits.append(byte); byte, cnt = 0, 0
            if cnt > 0:
                bits.append(byte << (8 - cnt))
        glyphs.append((w, h, yoff, off, pitch))

    with open(OUT_H, 'w', encoding='utf-8') as f:
        f.write("/* Auto-generated by gen_font.py: real 1bpp font, src %s, size=%d */\n"
                % (TTF_PATH, SIZE))
        f.write("#ifndef __FONT_H\n#define __FONT_H\n#include \"ht32.h\"\n")
        f.write("#define FONT_FIRST %d\n#define FONT_LAST %d\n#define FONT_EM_H %d\n"
                % (FIRST, LAST, em_h))
        f.write("typedef struct { u16 w; u16 h; u16 yoff; u16 off; u16 pitch; } FONT_GLYPH;\n")
        f.write("extern const FONT_GLYPH g_font_glyphs[%d];\n" % (LAST - FIRST + 1))
        f.write("extern const u8 g_font_bits[];\n#endif\n")

    with open(OUT_C, 'w', encoding='utf-8') as f:
        f.write("/* Auto-generated by gen_font.py: real font bitmap (1bpp, MSB first, row-major) */\n")
        f.write("#include \"font.h\"\n")
        f.write("const FONT_GLYPH g_font_glyphs[%d] = {\n" % (LAST - FIRST + 1))
        for (w, h, yoff, off, pitch) in glyphs:
            f.write("  {%d,%d,%d,%d,%d},\n" % (w, h, yoff, off, pitch))
        f.write("};\n")
        f.write("const u8 g_font_bits[] = {\n")
        for i in range(0, len(bits), 16):
            f.write("  " + ",".join("0x%02X" % b for b in bits[i:i + 16]) + ",\n")
        f.write("};\n")
    print("OK glyphs=%d bits=%d bytes" % (len(glyphs), len(bits)))

if __name__ == "__main__":
    main()
